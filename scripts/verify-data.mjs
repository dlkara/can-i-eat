import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const app=fs.readFileSync('dist/app.js','utf8');
const context=vm.createContext({state:{testMode:false,foodAllergies:[]}});
vm.runInContext(fs.readFileSync('dist/products.js','utf8')+'\n'+app.slice(0,app.indexOf('const ICONS=')),context);
const read=expression=>JSON.parse(vm.runInContext(`JSON.stringify(${expression})`,context));
const result=[];
function check(name,actual,expected){assert.deepEqual(actual,expected,name);result.push({name,actual});}
const records=read('PRODUCTS');
const added=['real-madegood-choc-bar-24','real-madegood-berry-bar-24','real-madegood-strawberry-bites-24'];
const both=['real-itsbetter-mango-30','real-itsbetter-blackrice-30'];
check('실제 상품 총 25개',records.length,25);
check('미등록 기준 비교 가능한 기록 23개',read('PRODUCTS.filter(p=>hasEvidence(p)).length'),23);
check('맛밤 제조환경 미확인',records.find(p=>p.id==='p01').facilityStatus,'UNKNOWN');
for(const p of records){assert.ok(['www.kurly.com','www.madegoodfoods.com'].includes(new URL(p.sourceUrl).hostname));assert.ok(p.labelUrl);assert.equal(p.checkedAt,[...added,...both].includes(p.id)?'2026-10-10':'2026-10-08');assert.ok(/\d+(?:\.\d+)?(?:g|mL|L)/.test(p.name));}
check('포테토칩 실제 직접 함유',records.find(p=>p.id==='p03').direct,['대두']);
check('포카칩 표시 함유',records.find(p=>p.id==='p02').direct,['우유','대두']);
check('새우깡 표시 함유',records.find(p=>p.id==='real-shrimp-90').direct,['밀','새우','대두','우유']);
check('미등록 시 맛밤·포카리스웨트 제외',read('recommendationCandidates().map(p=>p.id)'),records.filter(p=>!['p01','real-pocari-1500'].includes(p.id)).map(p=>p.id));
context.state.foodAllergies=['복숭아'];
check('복숭아 저장: 제조환경·미확인 제외 후 후보 11개',read('recommendationCandidates().map(p=>p.id)'),['p03','real-shrimp-90','real-potatosnack-250','real-honeytwist-300','real-spicyshrimp-400','real-squid-260','real-jagalchi-300','real-ricesnack-320','real-postick-280',...both]);
context.state.foodAllergies=['우유'];
check('우유 저장: 기존 경고 제외, 신규 5개 후보',read('recommendationCandidates().length'),5);
context.state.foodAllergies=['메밀'];
check('메밀 저장: 셀렉스·MadeGood 미확인 제외 후 후보 19개',read('recommendationCandidates().length'),19);
check('밀 제외 과자: 직접 함유·제조환경 모두 제외',read('searchProducts("밀 없는 과자").items.map(p=>p.id)'),[added[2],...both]);
check('새우 제외 과자: 직접 함유·제조환경 모두 제외',read('searchProducts("제외: 새우 과자").items.map(p=>p.id)'),[added[2],...both]);
check('밀 제외 전체: 셀렉스·신규 5개·미확인 2개 표시',read('searchProducts("밀 없는 간식").items.map(p=>p.id)'),['p01','real-pocari-1500','real-selex-nuts-50',...added,...both]);
check('포카칩 이름 검색',read('searchProducts("포카칩").items.map(p=>p.id)'),['p02']);
check('검색 빈 결과',read('searchProducts("없는제품명XYZ").items.length'),0);
check('일반 데이터 중복 ID 없음',new Set(records.map(p=>p.id)).size,25);
check('메밀 기준 미확인 상품 5개',read('PRODUCTS.filter(p=>!hasEvidence(p)).map(p=>p.id)'),['p01','real-pocari-1500',...added]);
check('새 단백질바 닭고기 표시 반영',records.find(p=>p.id==='real-doctor-protein-50').direct,['우유','대두','땅콩','닭고기']);
check('보리차 제조환경 아황산류 반영',records.find(p=>p.id==='real-barley-500').facility.includes('아황산류'),true);
check('실제 에너지바 카테고리 5개',read('searchProducts("에너지바").items.length'),5);
check('실제 이온음료 카테고리 1개',read('searchProducts("이온음료").items.length'),1);
check('알레르기 표준 항목 외 임의 매핑 없음',read('PRODUCTS.every(p=>[...p.direct,...p.facility].every(a=>ALLERGENS.includes(a)))'),true);
context.state.foodAllergies=['밀'];
check('밀 저장: 표시 기록 기준 셀렉스+MadeGood+코코넛칩 추천',read('recommendationCandidates().map(p=>p.id)'),['real-selex-nuts-50',...added,...both]);
check('새 상품 3개 모두 제조사 시설 근거 보존',records.filter(p=>added.includes(p.id)).every(p=>p.facilitySourceUrl&&p.wheatEvidence&&p.name.includes('미국 표시')),true);
context.state.foodAllergies=['토마토'];
check('토마토 저장: 새 바 직접 함유·바이트 공유시설 전부 제외',read('recommendationCandidates().some(p=>p.manufacturer==="MadeGood")'),false);
check('토마토 제외 검색: 새 상품 전부 제외',read('searchProducts("토마토 없는 MadeGood").items.length'),0);
context.state.foodAllergies=['밀','복숭아'];
check('밀+복숭아: 기존 미확인 제외, 코코넛칩 2개만 추천',read('recommendationCandidates().map(p=>p.id)'),both);
check('밀+복숭아: 신규 미확인 사유를 항목별로 기록',read('unconfirmedFor(PRODUCTS.find(p=>p.id==="real-madegood-strawberry-bites-24"))'),['복숭아']);
context.state.foodAllergies=['밀'];
check('검색 제외의 미확인 항목도 비교',read('hasEvidence(PRODUCTS.find(p=>p.id==="real-madegood-strawberry-bites-24"),["밀","메밀"])'),false);
context.state.foodAllergies=['대두'];
check('대두 저장: 코코넛칩 직접 함유로 추천 제외',read('recommendationCandidates().filter(p=>p.manufacturer==="잇츠베러").length'),0);
check('대두 검색 제외: 코코넛칩 2개 제외',read('searchProducts("대두 없는 잇츠베러").items.length'),0);
context.state.foodAllergies=['아황산류'];
check('아황산류 저장: 코코넛칩 제조환경으로 추천 제외',read('recommendationCandidates().filter(p=>p.manufacturer==="잇츠베러").length'),0);
check('이산화황 원문 보존과 아황산류 매핑',records.filter(p=>both.includes(p.id)).every(p=>p.facilityLabel.includes('이산화황')&&p.facility.includes('아황산류')),true);
context.state.testMode=true;context.state.foodAllergies=['밀','새우'];
check('별도 가상 모드 유지',read('recommendationCandidates().length'),17);
check('가상 22개 실제 상품 혼입 없음',read('catalog().every(p=>p.isTest)'),true);
fs.mkdirSync('artifacts/qa',{recursive:true});fs.writeFileSync('artifacts/qa/wheat-peach-products-logic.json',JSON.stringify({checks:result.length,results:result},null,2));
console.log(`${result.length}개 실제 데이터·필터 검증 통과`);
